import { createClient } from "npm:@supabase/supabase-js@2";
import { corsHeaders } from "npm:@supabase/supabase-js@2/cors";

// Intentionally public: no user/session or request metadata is recorded.
Deno.serve(async (request) => {
  if (request.method === "OPTIONS") return new Response("ok", { headers: corsHeaders });
  const respond = (body: object, status = 200) => new Response(JSON.stringify(body), {
    status, headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
  if (request.method !== "POST") return respond({ error: "Method not allowed" }, 405);
  try {
    // Empty payload only. The timestamp is generated by the database.
    const body = await request.text();
    if (body.length > 2 || (body !== "" && body !== "{}")) return respond({ error: "No click details accepted" }, 400);
    const url = Deno.env.get("SUPABASE_URL");
    const key = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
    if (!url || !key) return respond({ error: "Logging unavailable" }, 503);
    const client = createClient(url, key, { auth: { persistSession: false } });
    const { error } = await client.from("volunteer_clicks").insert({});
    return error ? respond({ error: "Could not record click" }, 503) : respond({ recorded: true });
  } catch {
    return respond({ error: "Logging unavailable" }, 503);
  }
});